%!  sf_dbf(+Column_Spec, +Table_Name, +Label, ?HTML_Type, +FN, +FS, +Attributes) is det.
%
%   UI field based on database meta-data (type, width)
%
%   The name of the input is Column_Name with provision for
%   disambiguation by prepending an alias:
%   ==
%   Alias:Column_Name
%   ==
%   Note that Column_Spec is always simply the field name in the case
%   of checkbox input since the Choices list contains the column names.
%
%   If it is bound, HTML_Type is one of:
%   $ text : One line text input
%   $ textarea : Multiline textarea
%   $ date : Date input. Not required since the type is uniquely  determined by the column data type
%   $ radio(Choices) : Choices is a list of Choice_Name-Choice_Label e.g. [fish-'Fish', soup-'Soup']
%   $ timestamp : date-time input
%   $ 'select-one'(Choices) : list Choice_Name-Choice_Label e.g. [''-'', fish-'Fish', soup-'Soup']
%   $ checkbox(Choices) : Checkboxes representing boolean attributes. Choices is a list of Column_Name-Choice_Label e.g. [newsletter-'Newsletter', social_events-'Social Events']
%   $ number : Numeric input.  Not required since the type is uniquely  determined by the column data type
%
%   @arg Column_Spec atom Database attribute name or Alias:Column_Name
%   @arg Table_Name atom Database table name
%   @arg Label atom Field label
%   @arg HTML_Type see above
%   @arg FN atom identifies the form the field belongs to
%   @arg FS dict
%   @arg Attributes Additional HTML attributes

sf_dbf(Name, _, Label, HTML_Type, FN, FS, Attributes) -->
    { ground(HTML_Type),
      HTML_Type = checkbox(Choices),
      $,
      must_be(atom, Name),
      must_be(atom, Label),
      must_be(compound(checkbox(list(pair))), HTML_Type),
      must_be(atom, FN),
      must_be(dict, FS),
      must_be(list, Attributes)
    },
    sf_checkboxes(Name, Label, Choices, FN, FS, Attributes).

sf_dbf(Column_Spec, Table_Name, Label, HTML_Type, FN, FS, Attributes) -->
    { (   atom(Column_Spec)
      ->  Name = Column_Spec,
          Column_Name = Column_Spec
      ;   must_be(compound(atom:atom), Column_Spec),
          Name:Column_Name = Column_Spec
      ),
      must_be(atom, Table_Name),
      must_be(atom, Label),
      must_be(atom, FN),
      must_be(dict, FS),
      must_be(list, Attributes),
      (   odbc_connection(C),
          sql_table_column(C, Table_Name, Column_Name, type_name(Type_Name))
      ->  true
      ;   existence_error(database_column, Table_Name:Column_Name)
      ),
      $
    },
    dbf(Type_Name, Table_Name, Column_Name, Name, Label, HTML_Type, FN, FS, Attributes).


%! dbf(+Type_Name, +Table_Name, +Column_Name, +Name, +Label, +HTML_Type, +FN, +FS, +Attributes) is det.

:- det(dbf//9).

dbf(text, Table_Name, Column_Name, Name, Label, text, FN, FS, Attributes) -->
    { odbc_connection(C),
      sql_table_column(C, Table_Name, Column_Name, precision(Maxlength))   % precision gives the right answer; length seems to give 2*N presumably something to do with Unicode support
    },
    !,
    sf_text_input(Name, Label, FN, FS, [maxlength(Maxlength)|Attributes]).

dbf(text, Table_Name, Column_Name, Name, Label, textarea, FN, FS, Attributes) -->
    { odbc_connection(C),
      sql_table_column(C, Table_Name, Column_Name, precision(Maxlength))
    },
    !,
    sf_textarea(Name, Label, FN, FS, [maxlength(Maxlength)|Attributes]).

dbf(date, _, _, Name, Label, date, FN, FS, Attributes) -->
    !,
    sf_date_input(Name, Label, FN, FS, Attributes).

dbf(text, _, _, Name, Label, radio(Choices), FN, FS, Attributes) -->
    !,
    sf_radio_buttons(Name, Label, Choices, FN, FS, Attributes).

dbf(timestamptz, _, _, Name, Label, timestamp, FN, FS, Attributes) -->
    !,
    sf_datetime_input(Name, Label, FN, FS, Attributes).

dbf(int4, _, _, Name, Label, number, FN, FS, Attributes) -->

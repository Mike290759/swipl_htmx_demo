%!  sf_pairs_as_hx_vals(+Pairs, -HX_Vals) is det.
%
%   HX_Vals is the HTMX HX_Val representation of the data in Pairs
%
%   Note that @(null) is mapped to ''
%
%   In order for ad hoc form state values to be easily distinguished
%   from "real" (input field) values, the ad hoc names are required to
%   be upper case.
%
%   You can use sf_memberchk_hx_val/2 to retrieve values encoded by this
%   predicate.
%
%   The value part of a pair is converted back to a term in
%   sf_ui_value_to_internal_value/4
%
%   @arg Pairs list Key-Value i.e. Value can be an arbitrary Prolog term
%   @arg HX_Vals string

sf_pairs_as_hx_vals(Pairs, HX_Vals) :-
    must_be(list(compound(atom-any)), Pairs),
    map_nulls_check_names(Pairs, Atomed_Pairs),
    dict_pairs(Dict, _, Atomed_Pairs),
    atom_json_dict(HX_Vals, Dict, [as(string)]).


map_nulls_check_names([], []).
map_nulls_check_names([Name-V|T1], [Name-Value_As_Atom|T2]) :-
    (   V == @(null)
    ->  Value_As_Atom = "'"

    ;   term_to_string(V, Value_As_Atom)
    ),
    (   upcase_atom(Name, Name)
    ->  true

    ;   html_input_name_and_type(Name, _, _)
    ->  true

    ;   domain_error(hx_val_name_upper_case_expected, Name)
    ),
    map_nulls_check_names(T1, T2).



%!  sf_memberchk_hx_val(+Selector, +Form_Pairs) is semidet.
%
%   Retrieve pairs created by sf_pairs_as_hx_vals/2 from Form_Pairs with
%   memberchk/2 semantics.
%
%   The value from the UI is converted to a Prolog term
%
%   *|NOTE!|* Form_Pairs are =/2 terms (not -/2)
%
%   @arg Selector Name=Value
%   @arg Form_Pairs Name=Value pairs

sf_memberchk_hx_val(Name=Value, Form_Pairs) :-
    memberchk(Name=Atom, Form_Pairs),
    (   Atom == ''
    ->  Value = ''
    ;   string_to_term(Atom, Value)
    ).




%! sf_form(+Form_Pred, +FN, +Initial_Form_State) // is det.
%
%   @arg Form_Pred Since this is a meta-predicate Form_Pred is <Module>:<PredName> and identifies a predicate which renders a SWI form
%   @arg FN atom identifies a form @arg Initial_Form_State dict, may be empty

:- meta_predicate
    sf_form(4, +, +, ?, ?).

sf_form(Module:Form_Pred, FN, Initial_FS, A, B) :-
    dict_pairs(Initial_FS, #, Initial_Pairs),
    dict_pairs(FS, #, ['MODULE'-Module, 'FORM_PRED'-Form_Pred, 'FORM_NAME'-FN|Initial_Pairs]),
    call(Module:Form_Pred, FN, FS, A, B).




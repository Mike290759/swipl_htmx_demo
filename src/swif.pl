dbf(numeric, Table_Name, Column_Name, Name, Label, number, FN, FS, Attributes) -->
    { odbc_connection(C),
      sql_table_column(C, Table_Name, Column_Name, scale(Scale))
    },
    !,
    sf_number_input(Name, Label, Scale, FN, FS, Attributes).


%!  sf_valid_dbf_html_type(+HTML_Type) is det.
%
%   Raises exception if HTML_Type is not valid

sf_valid_dbf_html_type(HTML_Type) :-
    must_be(( oneof([text, textarea, date, timestamp, number])
            ; compound(radio(list(atom-atom)))
            ; compound('select-one'(list(compound((integer ; atom)-atom))))
            ; compound(datalist(atom))
            ; compound(checkbox(list(compound(atom-atom))))
            ), HTML_Type).


%! sf_radio_buttons(+Input_ID, +Label, +Choices, +FN, +FS, +Attributes) // is det.
%
%   SWIF labelled radio buttons field
%
%   The value stored in the FS is Input_ID: Choice_Name
%
%   @arg Input_ID atom or <atom>(<integer>) uniquely identifying the radio button group on a form
%   @arg Label atom Field label
%   @arg Choices list of Choice_Name-Choice_Label e.g. [fish-'Fish', soup-'Soup']
%   @arg FN atom identifies the form the field belongs to
%   @arg FS dict
%   @arg Attributes Additional HTML attributes

sf_radio_buttons(Input_ID, Label, Choices, FN, FS, Attributes) -->
    { must_be_input_id(Input_ID),
      must_be(atom, Label),
      must_be(list(compound(atom-atom)), Choices),
      must_be(atom, FN),
      must_be(dict, FS),
      must_be(list, Attributes),
      $
    },
    html([\input_label(Attributes, [style('font-size: 13px;')], b(Label)),
          div([style('display: flex; border: none')],
              \radio_button_inputs(Choices, Input_ID, FN, FS, Attributes))]).


%! radio_button_inputs(+Choices, +Input_ID, +FN, +FS, +Attributes) is det.

radio_button_inputs([], _, _, _, _) -->
    [].
radio_button_inputs([Choice_Name-Choice_Label|T], Input_ID, FN, FS, Attributes) -->
    { $,
      HTML_Type = radio,
      (  term_to_atom(Input_ID, Input_ID_Atom),
         Choice_Name == FS.get(Input_ID_Atom)
      -> Attributes_1 = [checked|Attributes]
      ;  Attributes_1 = Attributes
      ),
      html_typed_name(Input_ID, HTML_Type, HTML_Typed_Name),
      phrase(input_attributes(Input_ID,
                              FN,
                              FS,
                              HTML_Type,
                              [],
                              [id(HTML_Typed_Name),
                               name(HTML_Typed_Name),   % A radio group is defined by giving each of radio buttons in the group the same name
                               value(Choice_Name),
                               type(HTML_Type)|Attributes_1]),
             Attributes_2)
    },
    html(div([style('display: flex; border: none')],
             [input([id(HTML_Typed_Name),     % Hidden input to overcome the problem of unselected radio buttons not
                     name(HTML_Typed_Name),   % appearing in the form state, see https://www.trickspanda.com/set-value-unchecked-checkbox/
                     type(hidden),
                     value('')]),
              input(Attributes_2),
              \input_label(Attributes, [style('font-size: 13px; margin-left:5px;margin-right:10px;'), for(HTML_Typed_Name)], Choice_Label)])),
    radio_button_inputs(T, Input_ID, FN, FS, Attributes).




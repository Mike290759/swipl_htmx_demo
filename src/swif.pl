%! form_to_pairs(+Equal_Pairs, -Pairs) is det.
%
%  @arg Equal_Pairs from the form
%  @arg Pairs Name-Internal_Value
%
%  See sf_ui_value_to_internal_value/4

form_to_pairs([], []).
form_to_pairs([Form_Equal_Pair|T1], [Name-Internal_Value|T2]) :-
    must_be(compound(atom=atom), Form_Equal_Pair),
    $,
    Form_Equal_Pair = (UI_Name=UI_Value),
    (   sf_ui_value_to_internal_value(UI_Name, UI_Value, Name, V)
    ->  Internal_Value = V
    ;   domain_error(invalid_form_field_name, UI_Name)
    ),
    form_to_pairs(T1, T2).



%! sf_ui_value_to_internal_value(+UI_Name:atom, +UI_Value:atom, -Name:atom, -Internal_Value) is semidet.
%
%    Extract and convert a data pair received from the UI into its Name
%    and internal value (date/3 etc)
%
%    There are three cases:
%    1. UI_Name is upper case e.g. 'FORM_NAME'. The UI_Value is
%    a Prolog atom representing the original data item coded by
%    sf_pairs_as_hx_vals/2. The value returned (Internal_Value)
%    is the original Prolog term.
%
%    2. UI_Name is Name:<type> e.g. booking_date:date in which case the
%    type information is extracted from <type>. N must be lower case
%
%    3. UI_Name is an upper case ad hoc name e.g. table cell context
%    added through HX_Vals, see sf_modal_popup_attributes//4
%
%    FAILS otherwise
%
%    Note that "real" form values are always typed (case 2 above) and
%    such pairs can be distinguished because their name is lower case.
%    In all other cases the name must be upper case.

sf_ui_value_to_internal_value(UI_Name, UI_Value, Name, Internal_Value) :-
    must_be(atom, UI_Name),
    must_be(atom, UI_Value),
    $,
    (   downcase_atom(UI_Name, UI_Name),   % Test for all lower case
        html_input_name_and_type(UI_Name, Name, HTML_Type)
    ->  ui_to_internal_value(UI_Value, HTML_Type, Internal_Value)

    ;   upcase_atom(UI_Name, UI_Name)      % Test for all upper case
    ->  Name = UI_Name,
        (   UI_Value == ''
        ->  Internal_Value = @(null)
        ;   string_to_term(UI_Value, Internal_Value)
        )
    ).


%!  ui_to_internal_value(+UI_Value, +HTML_Type, -Internal_Value) is det.
%
%   @arg HTML_Type date, 'datetime-local', number, checkbox, radio, text, textarea

ui_to_internal_value(Raw_UI_Value, HTML_Type, Value) :-
    $,
    (   atom(Raw_UI_Value)
    ->  sf_trim(Raw_UI_Value, UI_Value)
    ;   UI_Value = Raw_UI_Value
    ),

    (   UI_Value == ''
    ->  Value = @(null)

    ;   HTML_Type == date
    ->  atom_codes(UI_Value, UI_Codes),
        phrase((integer(Y), `-`, integer(M), `-`, integer(D)), UI_Codes),
        must_be(positive_integer, Y),
        must_be(between(1, 12), M),
        must_be(between(1, 31), D),
        Value = date(Y, M, D)

    ;   HTML_Type == 'datetime-local'
    ->  parse_time(UI_Value, iso_8601, Local_Time),  % e.g. UI_Value = '2026-09-26T17:18'
        Value = Local_Time

    ;   read_term_from_atom(HTML_Type, number:Scale, [])
    ->  sql_atom_to_numeric(UI_Value, V),
        (   integer(V),          % Need this because a UI input with scale > 0 can return text corresponding to integer
            Scale > 0            % and ODBC will error if an integer is passed to a non-integer numeric attribute
        ->  Value = V / 1
        ;   Value = V
        )

    ;   HTML_Type == checkbox
    ->   (   UI_Value == on
         ->  Value = @(true)
         ;   Value = @(false)
         )

    ;   HTML_Type == radio
    ->  Value = UI_Value

    ;   HTML_Type == data
    ->  string_to_term(UI_Value, Value)

    ;   otherwise
    ->  Value = UI_Value
    ).



%!  html_typed_name(+Input_ID, +HTML_Type, -HTML_Typed_Name) is det.
%
%   @arg Input_ID atom or <atom>(<integer>) uniquely identifying element on a form
%   @arg HTML_Type atom
%   @arg HTML_Typed_Name atom

html_typed_name(Input_ID, HTML_Type, HTML_Typed_Name) :-
    $,
    nonvar(Input_ID),
    ground(HTML_Type),
    format(atom(HTML_Typed_Name), '~w:`~w`', [Input_ID, HTML_Type]).  % Use backquotes because ordinary quote not allowed in HTML ID


%! html_input_name_and_type(+HTML_Typed_Name:atom, -Input_Name:atom, -HTML_Type:atom) is semidet.

html_input_name_and_type(HTML_Typed_Name, Input_Name, HTML_Type) :-
    atom(HTML_Typed_Name),
    string_to_term(HTML_Typed_Name, Input_Name_0:HTML_Type_Codes),
    atom_codes(HTML_Type, HTML_Type_Codes),
    term_to_atom(Input_Name_0, Input_Name).    % Need this to handle <name>(<integer>) ID's


%!  input_id(+Input_ID) is semidet.
%
%   Succeeds iff Input_ID is a valid input ID

input_id(Input_ID) :-
    nonvar(Input_ID),
    (   atom(Input_ID)
    ->  true

    ;   functor(Input_ID, Name, 1),
        atom(Name),
        arg(1, Input_ID, I),
        integer(I)
    ->  true
    ).

%!  must_be_input_id(+Input_ID) is det.

must_be_input_id(Input_ID) :-
    (   input_id(Input_ID)
    ->  true

    ;   type_error(input_id, Input_ID)
    ).


%!  must_be_input_id_template(+Input_ID) is det.

must_be_input_id_template(Input_ID) :-
    (   input_id(Input_ID)
    ->  true

    ;   nonvar(Input_ID),
        functor(Input_ID, Name, 1),
        atom(Name),
        arg(1, Input_ID, I),
        var(I)

    ;   type_error(input_id, Input_ID)
    ).


%!  sf_trim(+In, -Out) is det.
%
%   Trim leading and trailing whitespace.
%
%   The input argument can be either an atom, string or char/code list.
%   The output is the same type as the input.
%
%   See https://www.swi-prolog.org/pldoc/doc_for?object=split_string/4   "Examples"

sf_trim(In, Out) :-
    $,
    split_string(In, "", "\t\s\n", [S]),
    (   atom(In)
    ->  atom_string(Out, S)
    ;   string(In)
    ->  Out = S
    ;   In = [C|_],
        integer(C)
    ->  string_codes(S, Out)
    ;   string_chars(S, Out)
    ).


%!  sf_trim_to_null(+In, -Out) is det.
%
%   Trim leading and trailing whitespace. If the resulting string is
%   empty, bind Out to @(null). If In is @(null), Out is @(null).
%
%   The input argument can be either an atom, string or char/code list.
%   The output is the same type as the input.

sf_trim_to_null(In, Out) :-
    In == @(null),
    !,
    Out = @(null).

sf_trim_to_null(In, Out) :-
    sf_trim(In, Trimmed),
    (   Trimmed == ''
    ->  Out = @(null)

    ;   Trimmed == []
    ->  Out = @(null)

    ;   Trimmed == ""
    ->  Out = @(null)

    ;   Out = Trimmed
    ).


%!   sf_internal_to_ui_value(+Internal_Value, +HTML_Type, -UI_Value) is det.

sf_internal_to_ui_value(Internal_Value, HTML_Type, UI_Value) :-
    $,
    (   (  HTML_Type == checkbox
        ;  HTML_Type == radio
        )
    ->  (   Internal_Value == @(null)
        ->  UI_Value = false

        ;   Internal_Value == @(true)
        ->  UI_Value = true

        ;   Internal_Value == @(false)
        ->  UI_Value = false
        )

    ;   Internal_Value == @(null)
    ->  UI_Value = ''

    ;   HTML_Type == date
    ->  Internal_Value = date(Y, M, D),
        format(atom(UI_Value), '~w-~|~`0t~w~2+-~|~`0t~w~2+', [Y, M, D])

    ;   HTML_Type == 'datetime-local'
    ->  format_time(atom(UI_Value), '%Y-%m-%dT%H:%M', Internal_Value)   % SWI Timestamp

    ;   HTML_Type = number:Scale
    ->  format(atom(UI_Value), '~*f', [Scale, Internal_Value])

    ;   otherwise
    ->  UI_Value = Internal_Value
    ).


%! consequences(+Module:atom, +FN:atom, +Trigger_Input_ID:atom, +FS_In:dict, -FS_Out:dict) is det.
%
%   Compute the consequences of the value associated with field
%   value changing.
%
%   The rules are considered top down. If a rule has any input which has
%   been updated either by being input from the form or by being set
%   by another rule firing, the rule is called and if it succeeds it is
%   removed from the list of rules to be considered. An input does not
%   necessarily have to change value to be considered an input
%   capable of causing a rule to fire. The outputs of the rule are used
%   to update the state and the process begins again, considering the
%   rules from the top down.
%
%   A rule may leave an output unbound in which case the state is not
%   updated by that particular output.
%
%   Note that the rules must be defined in the module containing
%   the form definition (the module containing the sf_form/2 directive)
%   FN.

consequences(Module, FN, Trigger_Input_ID, FS0, FS1) :-
    findall(Clause_Reference,
            clause(Module:sf_rule(_, _, _, _, _, _), _, Clause_Reference),
            Clause_References),
    fire(Clause_References, Trigger_Input_ID, FN, [Trigger_Input_ID], FS0, FS1).


%! fire(+Clause_References, +Trigger_Input_ID, +FN, +Changed_Input_IDs, +FS_In, -FS_Out)
%
%   @arg Clause_References rule clause references
%   @arg Changed_Input_IDs list of keys of changed fields

fire([], _, _, _, FS, FS).

fire([Clause_Reference|T], Trigger_Input_ID, FN, Changed_Input_IDs, FS0, FS2) :-
    clause(Module:sf_rule(Rule_ID, FN, Trigger_Input_ID, _, Inputs, _), _, Clause_Reference),
    bindings(Inputs, Input_IDs, FS0),                       % Bind all input values
    intersection(Changed_Input_IDs, Input_IDs, [_|_]),      % Allow rule to fire iff at least one input has changed AND bind the array index I in keys of the form <atom>(I)
    call(Module:sf_rule(Rule_ID, FN, Trigger_Input_ID, FS0, Inputs, Outputs)),
    debug(swif, 'FIRED rule : ~w', [Module:Rule_ID]),
    !,
    update_state(Outputs, FN, New_Changed_Input_IDs, FS0, FS1),
    fire(T, Trigger_Input_ID, FN, New_Changed_Input_IDs, FS1, FS2).

fire([_|T], Trigger_Input_ID, FN, Changed_Input_IDs, FS0, FS1) :-
    fire(T, Trigger_Input_ID, FN, Changed_Input_IDs, FS0, FS1).


%! bindings(+Inputs:pairs, -Input_IDs, +FS) is det.

bindings([], [], _).
bindings([Input_ID-Value|T1], [Input_ID|T2], FS) :-
    (   atom(Input_ID)
    ->  Value = FS.get(Input_ID)

    ;   get_dict(Key, FS, V),
        string_to_term(Key, Input_ID)
    ->  Value = V
    ),
    !,
    bindings(T1, T2, FS).
bindings([_|T1], T2, FS) :-
    bindings(T1, T2, FS).


update_state([], _, [], FS, FS).
update_state([Input_ID-Value|T1], FN, [Input_ID|T2], FS0, FS2) :-
    nonvar(Value),
    term_to_atom(Input_ID, Input_ID_Atom),
    _ = FS0.Input_ID_Atom,  % The 'dot' access will give an exception if the field does not exist in the form state
    !,
    FS1 = FS0.put(Input_ID_Atom, Value),
    update_state(T1, FN, T2, FS1, FS2).
update_state([_|T], FN, Input_Names, FS0, FS1) :-
    update_state(T, FN, Input_Names, FS0, FS1).




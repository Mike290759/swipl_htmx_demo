%!   sf_hx_trigger_header(+JSON) is det.
%
%    Add an HX-Trigger header as per
%    https://htmx.org/headers/hx-trigger/ to trigger client side actions on the target element within a response to htmx.
%
%    Note that you can only have *one* such header in a page
%
%    The primary functor in JSON is the event name.
%
%    *|Example 1|*
%    ==
%    sf_hx_trigger_header(#{booking_event:''})
%    ==
%    ==
%    <div hx-trigger="booking_event from:body" hx-get="/example"></div>
%    ==
%
%    *|Example 2|*
%    ==
%    sf_hx_trigger_header(#{booking_event:'', my_event:{foo: 1, bar:
%    2}}) == == document.addEventListener("my_event", function(evt){
%    alert(evt.foo); }) ==

sf_hx_trigger_header(JSON) :-
    http_add_header('HX-Trigger', JSON).


%!  http_add_header(+HTTP_Header_Name:atom, +JSON:dict)
%
%   See https://swi-prolog.discourse.group/t/additional-http-headers-with-reply-html-page-2-3/3624
%
%   Use to add an HX-Trigger header that can be listened to by HTMX
%   hx-trigger e.g. to refresh a form when underlying data has changed

http_add_header(HTTP_Header_Name, JSON) :-
    format('~w: ', [HTTP_Header_Name]),
    json_write(current_output, JSON),     nl(current_output).



/** <module> SWIF
SWIF (SWI Forms) is a lightweight web application framework based on:
  $ Pure CSS: https://purecss.io/
  $ PostgreSQL: https://www.postgresql.org/
  $ HTMX: https://htmx.org/
  $ Hyperscript: https://hyperscript.org/
  $ SWI Prolog: https://www.swi-prolog.org/

This framework is intended for the rapid development of form-oriented web applications using the good looks of
Pure CSS, the platform independence of PostgreSQL, the
hypertext-for-everything capabilities of HTMX and Hyperscript (all
coding done on the server side) and a forward chaining form rules engine
that simplifies form-based application devbelopment all integrated with
SWI Prolog.

---++ SWI Forms
Use sf_form//3 to create a SWI Form. The first argument specifies a goal
which ultimately creates UI elements through predicates such as
sf_text_input//5 and friends. The actual HTML form is typically created
by sf_form_htmx//3.

Events generated by the UI elements are
handled by "rules" (see _|Rules|_ section below).

*|Example Usage|*

==
booking_sheet(Request) :-
    FN = booking_form,
    FS = #{},
    reply_htmx(\sf_form(booking_sheet, FN, FS)).   % Render the form


% The following DCG defines the form.
%
% FS contains the form state.

booking_sheet(FN, FS) -->
    html(\sf_form_htmx(FN,
                     [fieldset([class('pure-form pure-form-stacked'), style('border: none')],
                               [\sf_dbf(start_date, booking, 'Start Date', date, FN, FS, []),
                                \booking_time_slot(start_slot, 'Start Time', FN, FS, [])
                                ...])],
                     [])).
==


---+++ Hidden Fields
To implement a hidden field use a "normal" field and set it to hidden or
use the sf_data//3 object

e.g.
==
\sf_text_input(status, 'Status', FN, FS, [hidden])
==
This can make debugging easier as you can comment out the hidden
attribute and view the value.

---++ Rules
sf_rule/6 clauses map user-initiated events to form state changes
as well as application state changes (typically database updates).
The sf_rule/6 clauses are defined in form modules (modules with
sf_form/2 directives.

==
sf_rule(+Rule_ID, +FN, +Trigger_Input_ID, +FS, +Inputs, -Outputs) is semidet.
==
  $ Rule_ID : atom identifies a rule for debugging and logging purposes
  $ FN : atom identifies the form the field belongs to
  $ Trigger_Input_ID : atom or <atom>(<integer>) uniquely identifying element on a form
  $ FS : dict the dict tag is the form name
  $ Inputs : a list of id-value pairs identifying the inputs to the rule. id is an atom or a term name(I) where I is an integer >= 0
  $ Outputs : a list of name-value pairs identifying the ouputs of the rule

The name of each Input identifies an element of FS. Where the
name if a term Name(I), the Name identifies an element of FS
containing a list. This allows an array type of input object e.g. a
delete button on a set of rows.

The Inputs *|must be defined explicitly in the head of the rule|*.
These are used to set up htmx triggers on the input fields i.e. if
an input field appears in a rule it will have an htmx trigger set
up to initiate an Ajax event and call the back end when a UI event
occurs.

*|Example Rule|*
==
sf_rule(populate, my_form, _, _, [populate-_], Outputs) :-
     dict_pairs(#{surname: 'Elston',
                  newsletter: 1,
                  weight: 92,
                  preferred_aircraft_type: 'c172',
                  comments: 'Loopy loo'}, _, Outputs).
==

---++ Data Representations

An _|Internal Value|_ is the Prolog
representation of a value received from the HTML front end.

| *|HTML Type|*      | *|Internal Value|*    | *|Database Type|*  |
| text               | atom                  | text               |
| textarea           | atom                  | text               |
| date               | date(Y, M, D)         | date               |
| datetime-local     | SWI Timestamp         | timestamptz        |
| number:0           | integer               | integer            |
| number:Scale       | Numerator/Denominator | numeric            |
| checkbox           | @(true), @(false)     | boolean            |
| radio              | atom                  | text               |
| select-one         | atom                  | text               |
| datalist           | atom                  | text               |

Note that it is the _|functor|_ of HTML_Type that is an actual HTML type

---++ Form State
The state of a form is
represented by a dict with tag #. The values are _|internal|_ values
e.g. date/3, Numerator/Denominator

The following values are included in the form state supplied when
processing an HTML event:
  $ TRIGGER_NAME : the name of the input field or button that initiated
    an event
  $ FORM_NAME : the name of the form which generated the
    event

---++ Error Handling
The general approach is not to let Prolog exceptions find their way back
to the front end but if they do a modal dialog is displayed.

---++ Dynamic Refreshing

Ideally the user interface would dynamically refresh via a server-based
event mechanism e.g. SSE (https://v1.htmx.org/extensions/server-sent-events/)
but I had no luck making this work. See sse_test.pl. Use polling
instead. I might have dodged a bullet - see https://dev.to/miketalbot/server-sent-events-are-still-not-production-ready-after-a-decade-a-lesson-for-me-a-warning-for-you-2gie


%!  sf_form_state(+Form_Pairs, -FS) is det.
%
%   This predicate has two functions:
%
%    1. Map UI values to internal values e.g. '2024-07-29' to date(2024,7,29)
%    2. Resolving missing values
%       To cope with the fact that unset radio
%       buttons and checkboxes do not appears in the form state, a
%       hidden field is added to ensure that a value _|does|_ exist in
%       the form state (see radio_button_inputs/5 and
%       checkbox_inputs/5). However this means that when there _|is|_ a
%       value in the state, the hidden field value appears as well. In
%       addition, every radio button input will contribute a value to
%       the form state, each with the same name, however a maximum of
%       one of them will have a non-null value. This predicate drops the
%       superfluous null values.
%
%   @arg Form_Pairs name=value pairs possibly with duplicate keys
%   @arg FS dict

sf_form_state(Form_Pairs, FS) :-
    sort(Form_Pairs, Sorted_Form_Pairs),
    form_to_pairs(Sorted_Form_Pairs, FS_Pairs_0),
    group_pairs_by_key(FS_Pairs_0, Grouped_Pairs),
    drop_duplicates(Grouped_Pairs, FS_Pairs),
    dict_pairs(FS, _, FS_Pairs).


%! drop_duplicates(+Grouped_Pairs, -FS_Pairs) is det.

drop_duplicates([], []).
drop_duplicates([Name-Group|T1], [Name-Value|T2]) :-
    $,
    (   Group = [V]
    ->  Value = V

    ;   member(V, Group),
        V \== @(null)
    ->  Value = V

    ;   Value = @(null)
    ),
    drop_duplicates(T1, T2).



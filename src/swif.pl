%! sf_select_one(+Input_ID, +Label, +Choices, +FN, +FS, +Attributes) // is det.
%
%   SWIF labelled combobox (drop down menu) field
%
%   To specify null i.e. no value selected you must supply a choice of
%   ''-''
%
%   @arg Input_ID atom or <atom>(<integer>) uniquely identifying element on a form
%   @arg Label atom Field label
%   @arg Choices list of Choice_Name-Choice_Label e.g. [''-'',fish-'Fish', soup-'Soup']. Choice_Name is also permitted to be an integer
%   @arg FN atom identifies the form the field belongs to
%   @arg FS dict
%   @arg Attributes Additional HTML attributes

sf_select_one(Input_ID, Label, Choices, FN, FS, Attributes) -->
    { must_be_input_id(Input_ID),
      must_be(atom, Label),
      must_be(list(compound((integer ; atom)-atom)), Choices),
      must_be(atom, FN),
      must_be(dict, FS),
      must_be(list, Attributes),
      $,
      HTML_Type = 'select-one',
      html_typed_name(Input_ID, HTML_Type, HTML_Typed_Name),
      (   term_to_atom(Input_ID, Input_ID_Atom),
          Selected_Value_Key = FS.get(Input_ID_Atom)
      ->  true
      ;   Selected_Value_Key = ''
      ),
      phrase(input_attributes(Input_ID,
                              FN,
                              FS,
                              HTML_Type,
                              [],
                              [id(HTML_Typed_Name),
                               name(HTML_Typed_Name),
                               type(HTML_Type)|Attributes]),
             Attributes_1)
    },
    html(div([class('pure-form pure-form-stacked')],
             [ \input_label(Attributes, [style('font-size: 13px;'), for(HTML_Typed_Name)], b(Label)),
               select(Attributes_1, \allowed_values(Choices, Selected_Value_Key, Attributes))])).


%!   allowed_values(+Choices, +Selected_Value_Key, +Attributes) is det.
%
%    See  https://stackoverflow.com/questions/5805059/how-do-i-make-a-placeholder-for-a-select-box
%
%    @arg Selected_Value_Key atom or @(null)

allowed_values([], _, _) -->
    [].
allowed_values([''-_|T], Key, Attributes) -->
    !,
    {(   memberchk(required, Attributes)
     ->  Text = '- please choose -',
         Option_Attributes = [selected, hidden, value('')]

     ;   Key == @(null)
     ->  Text = '',
         Option_Attributes = [selected, value('')]

     ;   Text = '',
         Option_Attributes = [value('')]
     )
    },
    html(option(Option_Attributes, Text)),
    allowed_values(T, Key, Attributes).
allowed_values([Key-Display_Text|T], Selected_Value_Key, Attributes) -->
    {(   Key == Selected_Value_Key
     ->  Option_Attributes = [selected, value(Key)]
     ;   Option_Attributes = [value(Key)]
     )},
    html(option(Option_Attributes, Display_Text)),
    allowed_values(T, Selected_Value_Key, Attributes).


%!   sf_datalist(+Input_ID, +Label, +FN, +FS, +Attributes) // is det.
%
%    SWIF labelled datalist - has typeahead to restrict the items which
%    show in a pop down list
%
%    See https://turriate.com/articles/using-datalist-for-typeahead-htmx
%
%    Note that Pure CSS doesn't handle the datalist input so that style
%    has to be applied explicity
%
%    @arg Input_ID atom or <atom>(<integer>) uniquely identifying element on a form
%    @arg Label atom Field label
%    @arg FN atom identifies the form the field belongs to
%    @arg FS dict @arg Attributes Additional HTML attributes

:- http_handler(swif(datalist), datalist, []).

sf_datalist(Input_ID, Label, FN, FS, Attributes) -->
    { must_be_input_id(Input_ID),
      must_be(atom, Label),
      must_be(atom, FN),
      must_be(dict, FS),
      must_be(list, Attributes),
      $,
      HTML_Type = datalist,
      html_typed_name(Input_ID, HTML_Type, HTML_Typed_Name),
      format(string(Target_0), '~w__target', [HTML_Typed_Name]),
      atomic_list_concat(Sub_Strings, ":", Target_0),
      atomic_list_concat(Sub_Strings, "_", Target),
      format(string(HX_Target), '#~w', [Target]),
      sf_pairs_as_hx_vals(['DATALIST_TRIGGER'-Input_ID], HX_Vals),
      (   term_to_atom(Input_ID, Input_ID_Atom),
          Internal_Value = FS.get(Input_ID_Atom)
      ->  sf_internal_to_ui_value(Internal_Value, HTML_Type, UI_Value),
          Attributes_1 = [value(UI_Value)|Attributes]
      ;   Attributes_1 = Attributes
